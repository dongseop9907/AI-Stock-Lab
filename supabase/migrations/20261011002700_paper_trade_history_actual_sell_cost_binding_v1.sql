-- AI Stock Lab
-- #5 PAPER Realism / Accounting Consistency Hardening
-- Actual SELL execution cost -> trade history binding V1
--
-- Problem proven by runtime numeric reconciliation:
--   Protective SELL RPC received broker_fee = 5.00 and sell_tax = 10.00,
--   while paper_trade_history stored exit_broker_fee = 4.02.
--
-- Root cause:
--   legacy trade-history attribution derives SELL fee rate from BUY execution
--   and derives sell tax from a fixed rate. That is appropriate only as a
--   fallback estimate, not when canonical SELL execution costs already exist.
--
-- Canonical hierarchy after this migration:
--   paper_protective_execution_fills_v2 actual broker_fee / sell_tax
--       -> paper_trade_history exit_broker_fee / sell_tax
--       -> total_transaction_cost
--       -> net_pnl
--
-- Entry fee allocation remains owned by the existing position fee-basis model.
-- Account cash / realized_pnl and production BUY/SELL execution RPCs are not
-- replaced by this migration.

begin;

create or replace function
  public.bind_paper_trade_actual_sell_cost_from_fill_v1()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_match_count integer := 0;
  v_trade_id uuid;
begin
  /*
   * execute_paper_protective_sell_v2 writes trade history first and the
   * protective execution fill immediately afterwards in the same transaction.
   *
   * Match the exact trade generated by that protective fill.
   */
  select
    count(*)::integer
  into
    v_match_count
  from public.paper_trade_history t
  where t.source_position_id = new.position_id
    and t.account_id = new.account_id
    and t.stock_code = new.stock_code
    and t.quantity = new.filled_quantity
    and t.exit_price = new.execution_price
    and t.closed_at is not null
    and abs(
      extract(
        epoch from (t.closed_at - new.observed_at)
      )
    ) <= 0.001;

  /*
   * Standalone synthetic/probe fill rows may intentionally exist without
   * creating a trade-history row. Do not break those fixtures.
   */
  if v_match_count = 0 then
    return new;
  end if;

  /*
   * Ambiguous accounting attribution must fail closed.
   */
  if v_match_count <> 1 then
    raise exception
      'PAPER_ACTUAL_SELL_COST_TRADE_MATCH_AMBIGUOUS:%',
      v_match_count;
  end if;

  select
    t.id
  into
    v_trade_id
  from public.paper_trade_history t
  where t.source_position_id = new.position_id
    and t.account_id = new.account_id
    and t.stock_code = new.stock_code
    and t.quantity = new.filled_quantity
    and t.exit_price = new.execution_price
    and t.closed_at is not null
    and abs(
      extract(
        epoch from (t.closed_at - new.observed_at)
      )
    ) <= 0.001
  limit 1;

  update public.paper_trade_history
  set
    exit_broker_fee =
      round(
        greatest(
          0,
          coalesce(new.broker_fee, 0)
        ),
        2
      ),

    sell_tax =
      round(
        greatest(
          0,
          coalesce(new.sell_tax, 0)
        ),
        2
      ),

    total_transaction_cost =
      round(
        coalesce(entry_broker_fee, 0)
        +
        greatest(
          0,
          coalesce(new.broker_fee, 0)
        )
        +
        greatest(
          0,
          coalesce(new.sell_tax, 0)
        ),
        2
      ),

    net_pnl =
      round(
        coalesce(
          gross_pnl,
          realized_pnl,
          0
        )
        -
        (
          coalesce(entry_broker_fee, 0)
          +
          greatest(
            0,
            coalesce(new.broker_fee, 0)
          )
          +
          greatest(
            0,
            coalesce(new.sell_tax, 0)
          )
        ),
        2
      ),

    net_return =
      case
        when coalesce(entry_amount, 0) > 0
          then
            round(
              coalesce(
                gross_pnl,
                realized_pnl,
                0
              )
              -
              (
                coalesce(entry_broker_fee, 0)
                +
                greatest(
                  0,
                  coalesce(new.broker_fee, 0)
                )
                +
                greatest(
                  0,
                  coalesce(new.sell_tax, 0)
                )
              ),
              2
            )
            /
            entry_amount
        else null
      end,

    cost_model_version =
      'PAPER_EXECUTION_COST_ATTRIBUTION_V3_ACTUAL_SELL_EXECUTION',

    cost_attribution_snapshot =
      coalesce(
        cost_attribution_snapshot,
        '{}'::jsonb
      )
      ||
      jsonb_build_object(
        'version',
          'PAPER_EXECUTION_COST_ATTRIBUTION_V3_ACTUAL_SELL_EXECUTION',

        'exitFeeSource',
          'PROTECTIVE_EXECUTION_FILL_V2_ACTUAL',

        'sellTaxSource',
          'PROTECTIVE_EXECUTION_FILL_V2_ACTUAL',

        'protectiveFillId',
          new.id,

        'actualExitBrokerFee',
          round(
            greatest(
              0,
              coalesce(new.broker_fee, 0)
            ),
            2
          ),

        'actualSellTax',
          round(
            greatest(
              0,
              coalesce(new.sell_tax, 0)
            ),
            2
          ),

        'protectiveFillTransactionCost',
          round(
            greatest(
              0,
              coalesce(new.total_transaction_cost, 0)
            ),
            2
          ),

        'roundTripTransactionCost',
          round(
            coalesce(entry_broker_fee, 0)
            +
            greatest(
              0,
              coalesce(new.broker_fee, 0)
            )
            +
            greatest(
              0,
              coalesce(new.sell_tax, 0)
            ),
            2
          )
      )

  where id = v_trade_id;

  if not found then
    raise exception
      'PAPER_ACTUAL_SELL_COST_TRADE_UPDATE_FAILED';
  end if;

  return new;
end;
$$;

drop trigger if exists
  trg_bind_paper_trade_actual_sell_cost_from_fill_v1
on public.paper_protective_execution_fills_v2;

create trigger
  trg_bind_paper_trade_actual_sell_cost_from_fill_v1
after insert
on public.paper_protective_execution_fills_v2
for each row
execute function
  public.bind_paper_trade_actual_sell_cost_from_fill_v1();

comment on function
  public.bind_paper_trade_actual_sell_cost_from_fill_v1()
is
  'Binds canonical protective SELL execution broker fee and sell tax from paper_protective_execution_fills_v2 into the exact paper_trade_history row, preserving position-level BUY entry-fee attribution and recomputing full round-trip total cost/net PnL.';

commit;
