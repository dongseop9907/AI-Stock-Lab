begin;

-- ============================================================
-- PAPER BUY EXECUTION EVENT IDEMPOTENCY V1
--
-- Goal:
--   The exact same incremental PAPER BUY execution event must
--   never debit cash / increase position / filled_quantity twice.
--
-- Design:
--   - Keep the validated V4 BUY execution contract unchanged.
--   - Add a V5 wrapper with the SAME arguments as V4.
--   - Derive a canonical event fingerprint from the complete
--     execution tuple, including canonical jsonb provenance.
--   - Lock the order row.
--   - Replay existing ledger result without invoking V4.
--   - First-seen event delegates to V4 and persists its result
--     in the same DB transaction.
--
-- A failed V4 call rolls back both execution mutations and the
-- ledger insert because all work is in one transaction.
-- ============================================================


create table if not exists
  public.paper_buy_execution_events_v1 (
    id bigint
      generated by default as identity
      primary key,

    order_id uuid
      not null,

    event_fingerprint text
      not null,

    execution_observed_at timestamptz
      not null,

    execution_price numeric
      not null,

    execution_price_source text
      not null,

    fill_quantity integer
      not null,

    broker_fee numeric
      not null
      default 0,

    execution_provenance jsonb
      not null,

    execution_result jsonb
      not null,

    created_at timestamptz
      not null
      default now(),

    constraint
      paper_buy_execution_events_v1_fingerprint_nonempty
      check (
        length(event_fingerprint) = 32
      ),

    constraint
      paper_buy_execution_events_v1_price_positive
      check (
        execution_price > 0
      ),

    constraint
      paper_buy_execution_events_v1_fill_quantity_positive
      check (
        fill_quantity > 0
      ),

    constraint
      paper_buy_execution_events_v1_broker_fee_nonnegative
      check (
        broker_fee >= 0
      ),

    constraint
      paper_buy_execution_events_v1_order_event_unique
      unique (
        order_id,
        event_fingerprint
      )
  );


create index if not exists
  idx_paper_buy_execution_events_v1_order_created
on public.paper_buy_execution_events_v1 (
  order_id,
  created_at desc,
  id desc
);


revoke all
on table public.paper_buy_execution_events_v1
from public;


grant select
on table public.paper_buy_execution_events_v1
to service_role;


comment on table
  public.paper_buy_execution_events_v1
is
  'Idempotency ledger for incremental PAPER BUY execution events. Same order + canonical event fingerprint can mutate execution state only once.';


create or replace function
  public.execute_paper_buy_order_with_execution_price_v5(
    p_order_id uuid,
    p_execution_price numeric,
    p_execution_observed_at timestamptz,
    p_execution_price_source text,
    p_execution_provenance jsonb,
    p_fill_quantity integer default null,
    p_broker_fee numeric default 0
  )
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_locked_order_id uuid;

  v_event_fingerprint text;

  v_existing_event
    public.paper_buy_execution_events_v1%rowtype;

  v_result jsonb;
begin
  if p_order_id is null then
    raise exception
      'PAPER_BUY_V5_ORDER_ID_REQUIRED';
  end if;

  if p_execution_price is null
    or p_execution_price <= 0
  then
    raise exception
      'PAPER_BUY_V5_EXECUTION_PRICE_INVALID';
  end if;

  if p_execution_observed_at is null then
    raise exception
      'PAPER_BUY_V5_EXECUTION_OBSERVED_AT_REQUIRED';
  end if;

  if nullif(
    trim(
      coalesce(
        p_execution_price_source,
        ''
      )
    ),
    ''
  ) is null then
    raise exception
      'PAPER_BUY_V5_EXECUTION_SOURCE_REQUIRED';
  end if;

  if p_execution_provenance is null then
    raise exception
      'PAPER_BUY_V5_EXECUTION_PROVENANCE_REQUIRED';
  end if;

  if p_fill_quantity is null
    or p_fill_quantity <= 0
  then
    raise exception
      'PAPER_BUY_V5_FILL_QUANTITY_INVALID';
  end if;

  if p_broker_fee is null
    or p_broker_fee < 0
  then
    raise exception
      'PAPER_BUY_V5_BROKER_FEE_INVALID';
  end if;


  /*
   * The jsonb text representation is canonical for object key
   * ordering inside PostgreSQL. Including its digest makes a new
   * quote/provenance event distinct while keeping an exact RPC
   * payload retry stable.
   *
   * We also include the primary execution tuple explicitly so
   * the identity is explainable and inspectable.
   */
  v_event_fingerprint :=
    md5(
      p_order_id::text
      || '|'
      || (
        extract(
          epoch
          from p_execution_observed_at
        )::numeric(30, 6)
      )::text
      || '|'
      || trim_scale(
        p_execution_price
      )::text
      || '|'
      || trim(
        p_execution_price_source
      )
      || '|'
      || p_fill_quantity::text
      || '|'
      || trim_scale(
        p_broker_fee
      )::text
      || '|'
      || md5(
        p_execution_provenance::text
      )
    );


  /*
   * Serialize all fills/replays for this order before reading the
   * event ledger. Row locking alone did not solve idempotency in
   * V2, but it guarantees the ledger check + V4 mutation + ledger
   * write are ordered per order.
   */
  select o.id
  into v_locked_order_id
  from public.paper_order_requests o
  where o.id = p_order_id
  for update;

  if not found then
    raise exception
      'ORDER_NOT_FOUND';
  end if;


  select *
  into v_existing_event
  from public.paper_buy_execution_events_v1 e
  where e.order_id =
      p_order_id
    and e.event_fingerprint =
      v_event_fingerprint
  limit 1;


  if found then
    return
      v_existing_event.execution_result
      ||
      jsonb_build_object(
        'idempotentReplay',
          true,

        'executionEventFingerprint',
          v_event_fingerprint,

        'idempotencyVersion',
          'PAPER_BUY_EXECUTION_EVENT_IDEMPOTENCY_V1'
      );
  end if;


  /*
   * Preserve ALL validated semantics:
   *   V5 -> V4 -> V3 -> V2
   *
   * V4 retains weighted filled_price correction.
   * V3 retains execution provenance persistence.
   * V2 retains risk/account/position/partial-fill accounting.
   */
  select
    public.execute_paper_buy_order_with_execution_price_v4(
      p_order_id =>
        p_order_id,

      p_execution_price =>
        p_execution_price,

      p_execution_observed_at =>
        p_execution_observed_at,

      p_execution_price_source =>
        p_execution_price_source,

      p_execution_provenance =>
        p_execution_provenance,

      p_fill_quantity =>
        p_fill_quantity,

      p_broker_fee =>
        p_broker_fee
    )
  into v_result;


  insert into
    public.paper_buy_execution_events_v1 (
      order_id,
      event_fingerprint,
      execution_observed_at,
      execution_price,
      execution_price_source,
      fill_quantity,
      broker_fee,
      execution_provenance,
      execution_result
    )
  values (
    p_order_id,
    v_event_fingerprint,
    p_execution_observed_at,
    p_execution_price,
    trim(
      p_execution_price_source
    ),
    p_fill_quantity,
    p_broker_fee,
    p_execution_provenance,
    v_result
  );


  return
    v_result
    ||
    jsonb_build_object(
      'idempotentReplay',
        false,

      'executionEventFingerprint',
        v_event_fingerprint,

      'idempotencyVersion',
        'PAPER_BUY_EXECUTION_EVENT_IDEMPOTENCY_V1'
    );
end;
$$;


revoke all
on function
  public.execute_paper_buy_order_with_execution_price_v5(
    uuid,
    numeric,
    timestamptz,
    text,
    jsonb,
    integer,
    numeric
  )
from public;


grant execute
on function
  public.execute_paper_buy_order_with_execution_price_v5(
    uuid,
    numeric,
    timestamptz,
    text,
    jsonb,
    integer,
    numeric
  )
to service_role;


comment on function
  public.execute_paper_buy_order_with_execution_price_v5(
    uuid,
    numeric,
    timestamptz,
    text,
    jsonb,
    integer,
    numeric
  )
is
  'PAPER BUY V5: per-order execution-event idempotency ledger. Exact repeated incremental fill payload returns stored result without re-debiting cash or mutating position/filled quantity. New event delegates atomically to V4.';


do $$
begin
  if to_regprocedure(
    'public.execute_paper_buy_order_with_execution_price_v5(uuid,numeric,timestamp with time zone,text,jsonb,integer,numeric)'
  ) is null then
    raise exception
      'PAPER_BUY_V5_DEPLOYMENT_CHECK_FAILED';
  end if;

  if not exists (
    select 1
    from pg_constraint c
    where c.conrelid =
      'public.paper_buy_execution_events_v1'::regclass
      and c.conname =
        'paper_buy_execution_events_v1_order_event_unique'
      and c.contype = 'u'
  ) then
    raise exception
      'PAPER_BUY_EVENT_LEDGER_UNIQUE_GUARD_MISSING';
  end if;
end;
$$;


notify pgrst, 'reload schema';

commit;
