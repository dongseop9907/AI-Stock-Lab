#!/usr/bin/env node
'use strict';

/**
 * Patch and execute V9.9.2.1.1 replay V2.
 *
 * Fix:
 * The generated replay copy already expects the replay BRIDGE version,
 * but it still retained the historical closure STATUS guard:
 *
 *   V9_8_CURRENT_CYCLE_CLOSED_AT_2026_10_01
 *
 * The bridge intentionally has its own explicit status:
 *
 *   V9_8_REPLAY_CLOSURE_BRIDGED_FOR_V9_9_READ_ONLY_RECONCILIATION
 *
 * This patch changes ONLY that status contract and the replay script version.
 * Reconciliation business logic is otherwise byte-for-byte inherited from
 * scripts/v9902-1-1-replay.cjs.
 *
 * No network.
 * No DB writes.
 */

const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const PATCHER_VERSION =
  'V9_9_2_1_1_REPLAY_V2_PRIOR_CLOSURE_STATUS_CONTRACT_FIX';

const INPUT_SCRIPT_VERSION =
  'V9_9_2_1_1_REPLAY_INCREMENTAL_WORKSET_CARRY_FORWARD_RECONCILIATION_FIELD_PATH_REPAIR';

const OUTPUT_SCRIPT_VERSION =
  'V9_9_2_1_1_REPLAY_V2_INCREMENTAL_WORKSET_CARRY_FORWARD_RECONCILIATION_FIELD_PATH_REPAIR';

const HISTORICAL_STATUS =
  'V9_8_CURRENT_CYCLE_CLOSED_AT_2026_10_01';

const BRIDGE_STATUS =
  'V9_8_REPLAY_CLOSURE_BRIDGED_FOR_V9_9_READ_ONLY_RECONCILIATION';

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function replaceExactlyOnce(source, from, to, label) {
  const first =
    source.indexOf(from);

  assert(
    first >= 0,
    `PATCH_TARGET_NOT_FOUND:${label}`,
  );

  const second =
    source.indexOf(
      from,
      first + from.length,
    );

  assert(
    second === -1,
    `PATCH_TARGET_NOT_UNIQUE:${label}`,
  );

  return (
    source.slice(0, first) +
    to +
    source.slice(first + from.length)
  );
}

function atomicWrite(file, content) {
  fs.mkdirSync(
    path.dirname(file),
    { recursive: true },
  );

  const tmp =
    `${file}.tmp-${process.pid}-${Date.now()}`;

  fs.writeFileSync(
    tmp,
    content,
    'utf8',
  );

  fs.renameSync(
    tmp,
    file,
  );
}

function main() {
  const root =
    path.resolve(__dirname, '..');

  const inputFile =
    path.join(
      root,
      'scripts',
      'v9902-1-1-replay.cjs',
    );

  const outputFile =
    path.join(
      root,
      'scripts',
      'v9902-1-1-replay-v2.cjs',
    );

  const bridgeFile =
    path.join(
      root,
      'logs',
      'opendart-corporate-action-cycle-closure-v9-8-11-13-replay-v2-v9-9-bridge.json',
    );

  assert(
    fs.existsSync(inputFile),
    'INPUT_REPLAY_SCRIPT_NOT_FOUND',
  );

  assert(
    fs.existsSync(bridgeFile),
    'V9_9_BRIDGE_FILE_NOT_FOUND',
  );

  const bridge =
    JSON.parse(
      fs.readFileSync(
        bridgeFile,
        'utf8',
      ).replace(/^\uFEFF/, ''),
    );

  assert(
    bridge.status ===
      BRIDGE_STATUS,
    `BRIDGE_STATUS_UNEXPECTED:${bridge.status}`,
  );

  assert(
    bridge.bridge
      ?.historicalVersionSpoofed === false,
    'BRIDGE_MUST_NOT_SPOOF_HISTORICAL_VERSION',
  );

  assert(
    bridge.bridge
      ?.carryForwardContract
      ?.total === 55,
    `BRIDGE_CARRY_FORWARD_NOT_55:${bridge.bridge?.carryForwardContract?.total}`,
  );

  assert(
    bridge.bridge
      ?.physical028080RepairOutstanding === true,
    'EXPECTED_028080_PHYSICAL_REPAIR_PENDING',
  );

  assert(
    bridge.bridge
      ?.physical028080RepairAddedToCarryForward === false,
    '028080_MUST_NOT_BE_IN_CARRY_FORWARD_55',
  );

  let source =
    fs.readFileSync(
      inputFile,
      'utf8',
    );

  source =
    replaceExactlyOnce(
      source,
      INPUT_SCRIPT_VERSION,
      OUTPUT_SCRIPT_VERSION,
      'REPLAY_SCRIPT_VERSION',
    );

  source =
    replaceExactlyOnce(
      source,
      HISTORICAL_STATUS,
      BRIDGE_STATUS,
      'PRIOR_CLOSURE_STATUS_GUARD',
    );

  // Keep outputs distinct from failed replay V1.
  source =
    replaceExactlyOnce(
      source,
      'opendart-corporate-action-workset-carryforward-reconciliation-v9-9-2-1-1-replay.json',
      'opendart-corporate-action-workset-carryforward-reconciliation-v9-9-2-1-1-replay-v2.json',
      'OUTPUT_ARTIFACT_PATH',
    );

  const header =
    `/**\n` +
    ` * GENERATED BY ${PATCHER_VERSION}\n` +
    ` * Only replay closure STATUS contract was changed.\n` +
    ` * Original reconciliation business logic is preserved.\n` +
    ` */\n\n`;

  atomicWrite(
    outputFile,
    header + source,
  );

  console.log(
    JSON.stringify(
      {
        status:
          'V9_9_2_1_1_REPLAY_V2_STATUS_CONTRACT_PATCH_READY',

        version:
          PATCHER_VERSION,

        inputScript:
          'scripts/v9902-1-1-replay.cjs',

        outputScript:
          'scripts/v9902-1-1-replay-v2.cjs',

        priorClosureStatus: {
          from:
            HISTORICAL_STATUS,

          to:
            BRIDGE_STATUS,
        },

        carryForwardTotal:
          55,

        physical028080RepairOutstanding:
          true,

        physical028080RepairAddedToCarryForward55:
          false,

        networkRequests:
          0,

        databaseWrites:
          0,

        nextAction:
          'EXECUTE_V9_9_2_1_1_REPLAY_V2',
      },
      null,
      2,
    ),
  );

  const child =
    spawnSync(
      process.execPath,
      [outputFile],
      {
        cwd: root,
        env: process.env,
        stdio: 'inherit',
      },
    );

  if (child.error) {
    throw child.error;
  }

  if (child.status !== 0) {
    process.exitCode =
      child.status ?? 2;
  }
}

try {
  main();
} catch (error) {
  console.error(
    JSON.stringify(
      {
        status:
          'V9_9_2_1_1_REPLAY_V2_STATUS_CONTRACT_PATCH_FAILED',

        version:
          PATCHER_VERSION,

        error:
          String(
            error?.message ??
            error,
          ),

        networkRequests:
          0,

        databaseWrites:
          0,

        productionApplied:
          false,
      },
      null,
      2,
    ),
  );

  process.exitCode = 2;
}
