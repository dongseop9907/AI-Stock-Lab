const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const ROOT = process.cwd();
const SCRIPTS = path.join(ROOT, "scripts");
const LOGS = path.join(ROOT, "logs");

const PRODUCER = path.join(
  SCRIPTS,
  "true-forward-oos-controlled-producer-evidence-run-v1.ts"
);

const RUNNER = path.join(
  SCRIPTS,
  "run-shadow-controlled-producer-0850.ps1"
);

const TASK_INSTALLER = path.join(
  SCRIPTS,
  "register-shadow-controlled-producer-0850-task.ps1"
);

const VERIFY = path.join(
  SCRIPTS,
  "verify-shadow-controlled-producer-0850-task.cjs"
);

const TASK_NAME = "AI Stock Lab - SHADOW 0850";

function fail(reason, extra = {}) {
  console.error(JSON.stringify({
    status: "AI_STOCK_LAB_SHADOW_0850_TASK_INSTALL_FAILED",
    reason,
    ...extra,
  }, null, 2));
  process.exitCode = 1;
}

function psq(value) {
  return "'" + String(value).replace(/'/g, "''") + "'";
}

if (!fs.existsSync(PRODUCER)) {
  fail("CONTROLLED_PRODUCER_NOT_FOUND", {
    expected: path.relative(ROOT, PRODUCER).replace(/\\/g, "/"),
  });
} else {
  fs.mkdirSync(SCRIPTS, { recursive: true });
  fs.mkdirSync(LOGS, { recursive: true });

  const rootPs = psq(ROOT);
  const producerPs = psq(PRODUCER);

  const runnerSource = [
    "# AI Stock Lab - SHADOW Controlled Producer 08:50 Runner",
    "# Generated by install-shadow-controlled-producer-0850-task.cjs",
    "# SHADOW evidence collection only.",
    "# Does NOT promote to PAPER and does NOT enable real trading.",
    "",
    '$ErrorActionPreference = "Continue"',
    "",
    "$Root = " + rootPs,
    "$Producer = " + producerPs,
    '$LogDir = Join-Path $Root "logs"',
    "",
    "New-Item -ItemType Directory -Force $LogDir | Out-Null",
    "Set-Location $Root",
    "",
    "$Now = Get-Date",
    '$Stamp = $Now.ToString("yyyyMMdd-HHmmss")',
    '$ResultFile = Join-Path $LogDir ("shadow-auto-0850-" + $Stamp + ".txt")',
    '$LatestFile = Join-Path $LogDir "shadow-auto-0850-latest.txt"',
    "",
    "& {",
    '    Write-Output "============================================================"',
    '    Write-Output "=== AI STOCK LAB SHADOW AUTO 08:50                       ==="',
    '    Write-Output "============================================================"',
    '    Write-Output ("Started Local Time = " + (Get-Date).ToString("yyyy-MM-dd HH:mm:ss zzz"))',
    '    Write-Output ("Computer           = " + $env:COMPUTERNAME)',
    '    Write-Output ("User               = " + $env:USERNAME)',
    '    Write-Output ""',
    '    Write-Output "=== CONTROLLED NORMAL PRODUCER ==="',
    "",
    '    & "C:\\Program Files\\nodejs\\npx.cmd" tsx --env-file=.env.local $Producer',
    "    $ProducerExit = $LASTEXITCODE",
    "",
    '    Write-Output ""',
    '    Write-Output "=== FINAL RESULT ==="',
    '    Write-Output ("Producer Exit = " + $ProducerExit)',
    '    Write-Output "SHADOW evidence collection only"',
    '    Write-Output "PAPER promotion NOT executed by this task"',
    '    Write-Output "REAL trading NOT enabled by this task"',
    '    Write-Output ("Finished Local Time = " + (Get-Date).ToString("yyyy-MM-dd HH:mm:ss zzz"))',
    "",
    "} *>&1 | Tee-Object -FilePath $ResultFile | Out-Host",
    "",
    "Copy-Item $ResultFile $LatestFile -Force -ErrorAction SilentlyContinue",
    "",
  ].join("\r\n");

  fs.writeFileSync(RUNNER, runnerSource, "utf8");

  const taskInstallerSource = [
    "# AI Stock Lab - register SHADOW 08:50 task",
    '$ErrorActionPreference = "Stop"',
    "",
    "$TaskName = " + psq(TASK_NAME),
    "$Runner = " + psq(RUNNER),
    '$PowerShellExe = "$env:SystemRoot\\System32\\WindowsPowerShell\\v1.0\\powershell.exe"',
    "",
    '$Action = New-ScheduledTaskAction -Execute $PowerShellExe -Argument (\'-NoProfile -ExecutionPolicy Bypass -File "\' + $Runner + \'"\')',
    '$Trigger = New-ScheduledTaskTrigger -Weekly -WeeksInterval 1 -DaysOfWeek Monday,Tuesday,Wednesday,Thursday,Friday -At 08:50',
    '$Settings = New-ScheduledTaskSettingsSet -WakeToRun -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 30) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries',
    '$CurrentUser = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name',
    '$Principal = New-ScheduledTaskPrincipal -UserId $CurrentUser -LogonType Interactive -RunLevel Limited',
    '$Task = New-ScheduledTask -Action $Action -Trigger $Trigger -Settings $Settings -Principal $Principal -Description "AI Stock Lab SHADOW controlled producer. Weekdays 08:50 local time. Fail-closed outside controlled window. No PAPER promotion or real trading."',
    "",
    "Register-ScheduledTask -TaskName $TaskName -InputObject $Task -Force | Out-Null",
    "",
    "$Registered = Get-ScheduledTask -TaskName $TaskName",
    "$Info = Get-ScheduledTaskInfo -TaskName $TaskName",
    "",
    "[pscustomobject]@{",
    "    TaskName = $Registered.TaskName",
    "    State = $Registered.State.ToString()",
    "    NextRunTime = $Info.NextRunTime",
    "    WakeToRun = [bool]$Registered.Settings.WakeToRun",
    "    StartWhenAvailable = [bool]$Registered.Settings.StartWhenAvailable",
    "    Enabled = ($Registered.State.ToString() -ne 'Disabled')",
    "    User = $CurrentUser",
    '    Schedule = "MON-FRI 08:50 local time"',
    "    Runner = $Runner",
    "} | ConvertTo-Json -Depth 5",
    "",
  ].join("\r\n");

  fs.writeFileSync(TASK_INSTALLER, taskInstallerSource, "utf8");

  const verifySource = `const { spawnSync } = require("child_process");

const taskName = ${JSON.stringify(TASK_NAME)};

if (process.platform !== "win32") {
  console.error(JSON.stringify({
    status: "AI_STOCK_LAB_SHADOW_0850_TASK_VERIFY_FAILED",
    reason: "WINDOWS_REQUIRED",
  }, null, 2));
  process.exitCode = 1;
} else {
  const ps = [
    "$ErrorActionPreference = 'Stop'",
    "$t = Get-ScheduledTask -TaskName '${TASK_NAME.replace(/'/g, "''")}'",
    "$i = Get-ScheduledTaskInfo -TaskName '${TASK_NAME.replace(/'/g, "''")}'",
    "$o = [pscustomobject]@{ TaskName = $t.TaskName; State = $t.State.ToString(); NextRunTime = $i.NextRunTime; WakeToRun = [bool]$t.Settings.WakeToRun; StartWhenAvailable = [bool]$t.Settings.StartWhenAvailable; Enabled = ($t.State.ToString() -ne 'Disabled') }",
    "$o | ConvertTo-Json -Depth 5",
  ].join("; ");

  const r = spawnSync(
    "powershell.exe",
    ["-NoProfile", "-ExecutionPolicy", "Bypass", "-Command", ps],
    { encoding: "utf8" }
  );

  if (r.status !== 0) {
    console.error(JSON.stringify({
      status: "AI_STOCK_LAB_SHADOW_0850_TASK_VERIFY_FAILED",
      exitCode: r.status,
      stderr: (r.stderr || "").trim(),
    }, null, 2));
    process.exitCode = 1;
  } else {
    let task = null;
    try {
      task = JSON.parse((r.stdout || "").trim());
    } catch {
      task = { raw: (r.stdout || "").trim() };
    }

    const checks = {
      taskName: task && task.TaskName === taskName,
      enabled: task && task.Enabled === true,
      wakeToRun: task && task.WakeToRun === true,
      startWhenAvailable: task && task.StartWhenAvailable === true,
    };

    const failed = Object.entries(checks)
      .filter(([, ok]) => ok !== true)
      .map(([k]) => k);

    console.log(JSON.stringify({
      status: failed.length === 0
        ? "AI_STOCK_LAB_SHADOW_0850_TASK_VERIFIED"
        : "AI_STOCK_LAB_SHADOW_0850_TASK_VERIFY_REVIEW",
      task,
      checks,
      failed,
      safety: {
        paperPromotionScheduled: false,
        realTradingEnableScheduled: false,
        shadowProducerOnly: true,
      },
    }, null, 2));

    process.exitCode = failed.length === 0 ? 0 : 1;
  }
}
`;

  fs.writeFileSync(VERIFY, verifySource, "utf8");

  if (process.platform !== "win32") {
    console.log(JSON.stringify({
      status: "AI_STOCK_LAB_SHADOW_0850_TASK_INSTALLER_GENERATED",
      note: "WINDOWS_REGISTRATION_SKIPPED_ON_NON_WINDOWS_SELF_TEST",
      generatedRunner: path.relative(ROOT, RUNNER).replace(/\\/g, "/"),
      generatedTaskInstaller: path.relative(ROOT, TASK_INSTALLER).replace(/\\/g, "/"),
      generatedVerifier: path.relative(ROOT, VERIFY).replace(/\\/g, "/"),
    }, null, 2));
    return;
  }

  const registration = spawnSync(
    "powershell.exe",
    [
      "-NoProfile",
      "-ExecutionPolicy",
      "Bypass",
      "-File",
      TASK_INSTALLER,
    ],
    {
      cwd: ROOT,
      encoding: "utf8",
    },
  );

  if (registration.status !== 0) {
    fail("TASK_REGISTRATION_FAILED", {
      exitCode: registration.status,
      stdout: (registration.stdout || "").trim(),
      stderr: (registration.stderr || "").trim(),
    });
    return;
  }

  let taskInfo = null;
  try {
    taskInfo = JSON.parse((registration.stdout || "").trim());
  } catch {
    taskInfo = { raw: (registration.stdout || "").trim() };
  }

  console.log(JSON.stringify({
    status: "AI_STOCK_LAB_SHADOW_0850_TASK_INSTALLED",
    task: taskInfo,
    generatedRunner:
      path.relative(ROOT, RUNNER).replace(/\\/g, "/"),
    generatedVerifier:
      path.relative(ROOT, VERIFY).replace(/\\/g, "/"),
    behavior: {
      schedule: "MON-FRI 08:50 LOCAL_TIME",
      wakeFromSleepRequested: true,
      runWhenMissed: true,
      lateRunStillFailClosedByProducerWindow: true,
      krxHolidayHandling:
        "PRODUCER_TRADING_DATE_GUARD",
      persistentInternalAutomationChanged: false,
    },
    safety: {
      shadowProducerOnly: true,
      paperPromotionScheduled: false,
      realTradingEnableScheduled: false,
      brokerOrderScheduled: false,
    },
    important:
      "WakeToRun can wake sleep/hibernate only when Windows/firmware wake timers permit it. It cannot power on a fully shut-down PC.",
    nextAction:
      "RUN_VERIFIER_AND_REVIEW_NEXT_RUN_TIME",
  }, null, 2));
}
